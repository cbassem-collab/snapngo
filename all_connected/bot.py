def send_tasks(assignments_dict) -> None:
    log_step(
        logger,
        "interaction send_tasks start",
        users=len(assignments_dict) if assignments_dict else 0,
        user_ids=list(assignments_dict.keys())[:20] if assignments_dict else [],
    )
    '''
    * Message users to give them new tasks *
    Takes the assignments dictionary generated by getAssignments() in messenger
    Format the tasks each user get into block messages. Send them to each 
        user respectively
    Returns nothing
    ''' 
    active_users = messenger.get_active_users_list()
    for user_id in assignments_dict:
        print(f'IN SEND TASKS: {user_id}', datetime.now())
        if BOT_ID != user_id and user_id in active_users:   
            try:
                channel_id = _get_dm_channel_id(user_id)
                for task_info in assignments_dict[user_id]:
                    task_type = task_info[7] if len(task_info) > 7 else "data_collection"
                    if task_type == "verification":
                        assignment_id = task_info[8]
                        context = feedback_collector.get_verification_context(assignment_id)
                        if context and context.get("image_path"):
                            try:
                                client.files_upload_v2(
                                    channel=channel_id,
                                    file=context["image_path"],
                                    title="Submission image",
                                )
                            except Exception as exc:
                                print(f"Failed to upload image for verification task {task_info[0]}: {exc}")
                        block = feedback_collector.build_verification_blocks(
                            assignment_id,
                            task_info[0],
                            image_url=None,
                        )
                        client.chat_postMessage(channel=channel_id, blocks=block, text="Verification task")
                        print("Send verification task!")
                    else:
                        block = generate_message(task_info, user_id)
                        client.chat_postMessage(channel=channel_id, blocks=block, text="Sending tasks!")
                        print("Send task!")
            except SlackApiError as e:
                assert e.response["ok"] is False and e.response["error"], f"Got an error: {e.response['error']}"
    log_step(logger, "send_tasks exit")


