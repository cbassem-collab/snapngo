@app.message()
def handle_message(payload, say):
    log_step(logger, "handle_message enter", has_files="files" in payload, user=payload.get("user"))
    """
    Takes the response from a message sent in any chat in which this Bot has
        access to.
    When on, constantly listens for new messages, the responds as dictated below.
    Returns nothing.
    """
    channel_id = payload.get('channel')
    user_id = payload.get('user')
    text = payload.get('text')

    log_step(
        logger,
        "interaction message",
        user_id=user_id,
        channel=channel_id,
        text_preview=(text or "")[:80],
        has_files="files" in payload,
    )
    # Handle certain responses
    if BOT_ID != user_id:
        if 'files' not in payload:
            msg = (text or "").strip()
            if msg == "?" or msg.lower() == "help":
                log_step(logger, "interaction help", user_id=user_id)
                say(info_page)
            # User only sends text without attaching an image
            elif msg.lower() == "task":
                log_step(logger, "interaction on_demand task", user_id=user_id)
                active_users = messenger.get_active_users_list()
                if user_id not in active_users:
                    say(
                        "You need to be an active participant to get tasks. "
                        "Reply `opt in` if you have opted out."
                    )
                else:
                    tid = task.generate_on_demand_task_for_user(user_id, DB_NAME or "")
                    if tid is None:
                        say("Could not create a task right now. Please try again later.")
                    else:
                        try:
                            task_info = messenger.get_task_list(user_id, tid)
                            send_tasks({user_id: [task_info]})
                            messenger.mark_assignment_pending_for_user(tid, user_id)
                            say("Here is a new task for you. Accept or reject it above.")
                        except Exception as exc:
                            log_step(logger, "interaction on_demand task failed", error=str(exc))
                            say("Something went wrong sending your task. Please try again.")
            elif msg.lower() == "account":
                log_step(logger, "interaction account", user_id=user_id)
                send_messages(
                    user_id,
                    generate_account_summary_block(user_id),
                    "Your account summary",
                )
            elif msg.lower() == "report":
                active_block = make_report_block(user_id)
                end_block = [block_headers['divider'], block_headers['ending_block']]
                dm_channel_id = _get_dm_channel_id(user_id)
                client.chat_postMessage(channel=dm_channel_id, blocks = active_block,text="")

                 # Sort pending tasks by start time
                pending_ids = messenger.get_pending_tasks(user_id)
                all_pending = [messenger.get_task_list(user_id, task_id) for task_id in pending_ids]
                sorted_pending = sorted(all_pending, key=lambda task_list: task_list[4])
                for task_list in sorted_pending:
                    pending_task = compact_task(task_list)
                    buttons = copy.deepcopy(default_btn)
                    buttons['block_id'] = str(task_list[0])
                    blocks = [pending_task, buttons]

                    client.chat_postMessage(channel=dm_channel_id, blocks = blocks, text="")

                client.chat_postMessage(channel=dm_channel_id, blocks = end_block,text="")
            elif msg.lower() == "opt in":
                messenger.update_account_status(user_id, "active")
                say("You have opted in for the day.")
            elif msg.lower() == "opt out":
                messenger.update_account_status(user_id, "inactive")
                say("You have opted out for the day.")
            else:
                say(sample_task)
        else:
            # User attaches more than one image
            print("text+file", datetime.now())
            print(payload)
            if len(payload['files']) > 1:
                log_step(logger, "interaction reject multi_file", user_id=user_id)
                say("*:large_orange_circle: You are attaching more than one file.* Reply `?` for more information.")
                return

            # User attaches a file that is not an image
            file = payload['files'][0]
            if "image" not in file['mimetype']:
                log_step(logger, "interaction reject not_image", user_id=user_id, mimetype=file.get("mimetype"))
                say("*:large_orange_circle: The file you attached is not an image.*\n Reply `?` for more information.")
                return
            task_id = payload['blocks'][0]['elements'][0]['elements'][0]['text']
            print("TASK ID:", task_id)
            if not task_id.isdigit():
                log_step(logger, "interaction reject bad_task_text", user_id=user_id, task_text=task_id[:50])
                say(":large_orange_circle: Please include *only the task number* in the text & attach that tasks's image.")
                return
            task_id = int(task_id)
            accepted_tasks = messenger.get_accepted_tasks(user_id)
            pending_tasks = messenger.get_pending_tasks(user_id)
            # The text the user enters isn't any of their assigned task numbers
            if messenger.check_time_window(task_id) == "expired":
                log_step(logger, "interaction reject expired", user_id=user_id, task_id=task_id)
                say(f''':large_orange_circle: Task {task_id} has already expired. Please pick another assigned task to finish.''')
            elif messenger.check_time_window(task_id) == "not started":
                log_step(logger, "interaction reject not_started", user_id=user_id, task_id=task_id)
                say(f''':large_orange_circle: Task {task_id} has not started yet. Please check the start time & time window and finish this task later.''')
            elif task_id not in accepted_tasks:
                log_step(logger, "interaction reject not_accepted", user_id=user_id, task_id=task_id, accepted_tasks=accepted_tasks)
                say(f":large_orange_circle: Task {task_id} is not one of your unfinished, accepted tasks. Your unfinished, accepted tasks are {accepted_tasks}")
                if task_id in pending_tasks:
                    say(f'''However, task {task_id} is one of your pending tasks. You can still complete the task by pressing the Accept button for task {task_id} and then submit your picture.''')
                return
            else:
                log_step(logger, "interaction image submit", user_id=user_id, task_id=task_id, file=file.get("name"))
                url = file["url_private_download"]
                path = get_pic(url, BOT_TOKEN, user_id, task_id)
                log_step(logger, "interaction image saved", user_id=user_id, task_id=task_id, path=path)
                result = messenger.submit_task(user_id, task_id, path)
                if isinstance(result, dict) and result.get("ok"):
                    amt = result.get("compensation", 0)
                    again = result.get("already_submitted")
                    log_step(
                        logger,
                        "interaction submit success",
                        user_id=user_id,
                        task_id=task_id,
                        compensation_added=amt,
                        resubmission=again,
                    )
                    if again and amt == 0:
                        say(
                            f"We updated your image for task *{task_id}*. "
                            f"Compensation was already added for this task. Reply `account` to see your balance."
                        )
                    else:
                        say(
                            f"We received your submission for task *{task_id}*. "
                            f"*+{amt} points* have been added to your account right away. "
                            f"Reply `account` to see your balance and completed tasks."
                        )
                elif result is True:
                    # Backward compat if submit_task still returns bool
                    say(
                        f"We received your submission for task *{task_id}*. "
                        f"Reply `account` to see your account status."
                    )
                else:
                    log_step(logger, "interaction submit failed", user_id=user_id, task_id=task_id)
            #update database if image is NULL
        return #needs to be changed


